_TERMS = sorted(TERMS, key=lambda kv: len(kv[0]), reverse=True)


def translate(text):
    """把日文名翻成中文；遇到英文名或未知词就原样返回。"""
    out = text or ""
    buf = []
    i = 0
    while i < len(out):
        hit = None
        for jp, cn in _TERMS:
            if out.startswith(jp, i):
                hit = (jp, cn)
                break
        if hit is None:
            buf.append(out[i])
            i += 1
        else:
            buf.append(hit[1])
            i += len(hit[0])
    return "".join(buf)


def localize_mode(mode):
    """给 H mode 补上 ``label_jp`` / ``label_cn`` / ``type_cn``。"""
    if not mode:
        return mode
    jp = mode.get("label") or ""
    mode.setdefault("label_jp", jp)
    mode["label_cn"] = translate(jp) or jp
    type_jp = mode.get("type_jp") or ""
    mode["type_cn"] = translate(type_jp) or type_jp
    mode.setdefault("type_jp", type_jp)
    return mode


def localize_modes(modes):
    """就地给整个目录补中文名，返回同一个列表。"""
    for mode in modes or []:
        localize_mode(mode)
    return modes


def label_of(mode):
    """界面/提示里用的中文名，取不到就退回日文原名。"""
    if not isinstance(mode, dict):
        return mode or ""
    return mode.get("label_cn") or mode.get("label") or mode.get("key") or ""
